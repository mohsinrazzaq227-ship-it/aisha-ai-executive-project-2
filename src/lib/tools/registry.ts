export const TOOL_IDS = Object.keys(TOOLS);

export function getTool(id: string): ToolDef {
  const tool = TOOLS[id];
  if (!tool) throw new Error(`Unknown tool "${id}" — the planner may only use registered tools.`);
  return tool;
}

export function toolParamsForDisplay(id: string): ToolParam[] {
  return TOOLS[id]?.params ?? [];
}
