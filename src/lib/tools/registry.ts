/**
 * Tool registry. The LLM (or the deterministic planner) can only ever reference
 * these declared tools with these declared parameters — it can never invent an
 * interface. Risk classification, approval requirements, timeouts, path scope
 * and validators all live here, and the execution layer enforces them.
 */

export type ToolParam = { name: string; type: string; required: boolean; description: string };

export type ToolDef = {
  id: string;
  description: string;
  defaultAgent: string;
  inputSchema: z.ZodTypeAny;
  params: ToolParam[];
  risk: RiskLevel;
  requiresApproval: boolean;
  timeoutMs: number;
  cancellable: boolean;
  pathScope: "none" | "workspace" | "documents" | "uploads";
  producesArtifacts: boolean;
  hostRequirement: "any" | "windows" | "unix";
  /** Human-readable label used in the approval dialog. */
  approvalLabel: string;
};

const p = (name: string, type: string, required: boolean, description: string): ToolParam => ({ name, type, required, description });

/** Patterns that make a shell command categorically unacceptable. */
export const FORBIDDEN_COMMAND_PATTERNS: { pattern: RegExp; reason: string }[] = [
  { pattern: /\brm\s+(-[a-zA-Z]*\s+)*\/(\s|$)/, reason: "Recursive delete of the filesystem root" },
  { pattern: /\brm\s+-[a-zA-Z]*r[a-zA-Z]*f?\s+[A-Za-z]:[\\/]?(\s|$)/i, reason: "Recursive delete of a whole drive" },
  { pattern: /\b(format|diskpart|mkfs(\.\w+)?)\b/i, reason: "Disk formatting / partitioning" },
  { pattern: /\bshutdown\b|\brestart-computer\b|\bstop-computer\b/i, reason: "Shutting down the machine" },
  { pattern: /\bdel\s+\/[sfq]\b.*\b[a-z]:\\?(\s|$)/i, reason: "Forced deletion of a drive" },
  { pattern: /\b(curl|wget|iwr|invoke-webrequest)\b[^|]*\|\s*(ba)?sh\b/i, reason: "Piping a remote script directly into a shell" },
  { pattern: /\b(iex|invoke-expression)\b.*\b(downloadstring|invoke-webrequest|iwr)\b/i, reason: "Executing remotely downloaded code" },
  { pattern: /-e(nc|ncodedcommand)\b/i, reason: "Base64-encoded command payload (obfuscation)" },
  { pattern: /\bset-mppreference\b|\badd-mppreference\b|\bdisable-windowsoptionalfeature\b/i, reason: "Disabling system security controls" },
  { pattern: /\bschtasks\s+\/create\b|\breg\s+delete\b/i, reason: "Persistence / registry tampering" },
  { pattern: /:\s*\(\)\s*\{.*\}\s*;\s*:/, reason: "Fork bomb" },
  { pattern: /\bnet\s+user\b.*\/add\b|\bnet\s+localgroup\b.*\/add\b/i, reason: "Creating accounts or elevating group membership" },
  { pattern: /\btakeown\b|\bicacls\b.*\/grant\b/i, reason: "Changing file ownership/permissions" },
];

export function validateShellCommand(command: string, allowedCommands: string[]): { ok: boolean; reason?: string; program?: string } {
  const trimmed = command.trim();
  if (trimmed.length === 0) return { ok: false, reason: "Empty command" };
  if (trimmed.length > 1200) return { ok: false, reason: "Command longer than the 1200 character limit" };
  for (const { pattern, reason } of FORBIDDEN_COMMAND_PATTERNS) {
    if (pattern.test(trimmed)) return { ok: false, reason: `Blocked by command validator: ${reason}` };
  }
  const program = trimmed.split(/\s|\||;/)[0].replace(/^["']|["']$/g, "").toLowerCase();
  const normalized = program.replace(/\.(exe|cmd|bat|ps1|sh)$/, "");
  if (allowedCommands.length > 0 && !allowedCommands.includes(normalized)) {
    return {
      ok: false,
      program: normalized,
      reason: `Program "${normalized}" is not in the configured allowlist (${allowedCommands.join(", ")}). Update config/app.json to widen the scope explicitly.`,
    };
  }
  return { ok: true, program: normalized };
}

